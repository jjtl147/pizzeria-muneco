const { createRequire } = require('node:module')
const herramientas = createRequire(process.env.TEST_TOOLS_PATH + '/package.json')
const { test, expect } = herramientas('@playwright/test')

test('cliente, vendedor y administrador: compra, cobro, venta, stock y roles', async ({ page }) => {
  const errores = []
  page.on('pageerror', (e) => errores.push(e.message))
  await page.route('https://placehold.co/**', (route) => route.abort())
  async function login(email) {
    await page.goto('/login')
    await page.getByLabel('Correo electrónico').fill(email)
    await page.getByLabel('Contraseña', { exact: true }).fill('Prueba123!')
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Cerrar sesión' })).toBeVisible()
  }
  async function salir() { await page.getByRole('button', { name: 'Cerrar sesión' }).click(); await expect(page.getByRole('link', { name: 'Iniciar sesión' })).toBeVisible() }
  await page.goto('/mis-pedidos')
  await expect(page).toHaveURL(/login/)
  await page.getByRole('link', { name: 'Regístrate' }).click()
  await page.getByLabel('Nombre', { exact: true }).fill('Nuevo cliente')
  await page.getByLabel('Correo electrónico').fill('nuevo@example.test')
  await page.getByLabel('Contraseña', { exact: true }).fill('Prueba123!')
  await page.getByLabel('Repetir contraseña').fill('Prueba123!')
  await page.getByRole('button', { name: 'Registrarme' }).click()
  await expect(page.getByText('Cuenta creada. Inicia sesión para comprar.')).toBeVisible()
  await login('nuevo@example.test')
  await page.goto('/catalogo')
  await page.getByLabel('Tamaño').selectOption({ label: 'Familiar — $20.00' })
  await page.getByRole('button', { name: 'Agregar al carrito' }).click()
  await page.getByRole('link', { name: 'Carrito (1)' }).click()
  await expect(page.getByText('Pizza prueba (Familiar)')).toBeVisible()
  await page.getByLabel('Dirección de entrega').fill('Calle prueba 123')
  await page.getByLabel('Teléfono de contacto').fill('70000000')
  await page.getByRole('button', { name: 'Confirmar pedido' }).click()
  await expect(page.getByText('Pedido #1 registrado correctamente.')).toBeVisible()
  await expect(page.getByText('PENDIENTE', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Pizza prueba (Familiar)')).toBeVisible()
  await salir()
  await login('vendedor@example.test')
  const tokenVendedor = await page.evaluate(() => sessionStorage.getItem('muneco_token'))
  await expect(page.getByRole('link', { name: 'Productos', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Pasar a en preparacion' }).click()
  await page.getByRole('button', { name: 'Pasar a en camino' }).click()
  await page.getByRole('button', { name: 'Pasar a entregado' }).click()
  await page.getByLabel('Pago del pedido 1').selectOption('QR')
  await page.getByRole('button', { name: 'Registrar cobro' }).click()
  await expect(page.getByText('Venta registrada', { exact: true })).toBeVisible()
  await page.goto('/operacion/productos')
  await expect(page.getByText('No tienes permisos para acceder a esta sección.')).toBeVisible()
  await page.goto('/operacion/ventas')
  await page.getByLabel('Producto y tamaño').selectOption({ label: 'Pizza prueba (Mediana) — $12.00' })
  await page.getByLabel('Cantidad', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Agregar producto' }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Confirmar venta' }).click()
  await expect(page.getByText('Venta registrada para el pedido #2.')).toBeVisible()
  await salir(); await login('admin@example.test')
  await page.getByRole('link', { name: 'Reportes', exact: true }).click()
  await expect(page.getByText('$44.00', { exact: true }).first()).toBeVisible()
  await page.getByRole('link', { name: 'Inventario', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Pizza prueba (Mediana)' })).toContainText('8')
  await page.getByRole('link', { name: 'Categorías', exact: true }).click()
  await page.getByLabel('Nombre', { exact: true }).fill('Bebidas test')
  await page.getByLabel('Descripción', { exact: true }).fill('Categoría de prueba')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  const categoria = page.getByRole('row').filter({ hasText: 'Bebidas test' })
  await expect(categoria).toBeVisible()
  await categoria.getByRole('button', { name: 'Editar', exact: true }).click()
  await page.getByLabel('Activa', { exact: true }).uncheck()
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(categoria).toContainText('No')
  await page.getByRole('link', { name: 'Productos', exact: true }).click()
  await page.getByLabel('Nombre de pizza o producto').fill('Pizza especial')
  await page.getByLabel('Tamaño (opcional)').fill('Personal')
  await page.getByLabel('Precio', { exact: true }).fill('8')
  await page.getByLabel('Stock inicial').fill('4')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  const producto = page.getByRole('row').filter({ hasText: 'Pizza especial (Personal)' })
  await expect(producto).toBeVisible()
  await producto.getByRole('button', { name: 'Editar', exact: true }).click()
  await page.getByLabel('Precio', { exact: true }).fill('9')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(producto).toContainText('$9.00')
  page.once('dialog', (dialog) => dialog.accept())
  await producto.getByRole('button', { name: 'Desactivar' }).click()
  await expect(producto).toContainText('No')
  await page.getByRole('link', { name: 'Inventario', exact: true }).click()
  const inventario = page.getByRole('row').filter({ hasText: 'Pizza especial (Personal)' })
  await inventario.getByRole('button', { name: 'Ajustar' }).click()
  await page.getByLabel('Stock actual', { exact: true }).fill('7')
  await page.getByLabel('Mínimo para alerta').fill('2')
  await page.getByRole('button', { name: 'Guardar stock' }).click()
  await expect(inventario).toContainText('7')
  await page.getByRole('link', { name: 'Usuarios y roles' }).click()
  const vendedor = page.getByRole('row').filter({ hasText: 'vendedor@example.test' })
  await vendedor.getByRole('button', { name: 'Editar roles' }).click()
  await page.getByLabel('CLIENTE', { exact: true }).check()
  await page.getByRole('button', { name: 'Guardar roles' }).click()
  await expect(vendedor).toContainText('CLIENTE')
  await vendedor.getByRole('button', { name: 'Editar roles' }).click()
  await page.getByLabel('VENDEDOR', { exact: true }).uncheck()
  await page.getByRole('button', { name: 'Guardar roles' }).click()
  await expect(vendedor).not.toContainText('VENDEDOR')
  const denegado = await page.request.get('http://127.0.0.1:5059/api/ventas', { headers: { Authorization: `Bearer ${tokenVendedor}` } })
  expect(denegado.status()).toBe(403)
  await vendedor.getByRole('button', { name: 'Editar roles' }).click()
  await page.getByLabel('VENDEDOR', { exact: true }).check()
  await page.getByRole('button', { name: 'Guardar roles' }).click()
  await expect(vendedor).toContainText('VENDEDOR')
  await page.getByRole('link', { name: 'Asistente', exact: true }).click()
  await expect(page.getByText('El asistente todavía no está disponible. El administrador debe configurar el servicio.')).toBeVisible()
  await salir(); await login('vendedor@example.test')
  await expect(page.getByRole('link', { name: 'Mis pedidos' })).toBeVisible()
  expect(errores).toEqual([])
})
